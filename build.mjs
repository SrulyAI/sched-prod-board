// Builds dist/ from app/: stamps the git sha (R6) and writes config.js from ../session.txt,
// which lives outside this repo, so the session is never committed.
// Usage: node build.mjs            (refuses to build from uncommitted changes)
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

const root = path.dirname(new URL(import.meta.url).pathname.replace(/^\/(\w:)/, '$1'));
const git = (...a) => execFileSync('git', a, { cwd: root, encoding: 'utf8' }).trim();

if (git('status', '--porcelain')) {
  console.error('Uncommitted changes: commit first, so the sha names this exact build.');
  process.exit(1);
}
const sha = git('rev-parse', 'HEAD');

const sessionFile = path.join(root, '..', 'session.txt');
const session = fs.readFileSync(sessionFile, 'utf8').match(/^session=(.+)$/m)?.[1].trim();
if (!session) throw new Error('no session in ../session.txt');
const API = 'https://hq.mega.dev/challenges/show-me-when/api';

const src = path.join(root, 'app');
const dist = path.join(root, 'dist');
fs.rmSync(dist, { recursive: true, force: true });
fs.mkdirSync(dist);
for (const f of fs.readdirSync(src)) fs.copyFileSync(path.join(src, f), path.join(dist, f));

const html = fs.readFileSync(path.join(dist, 'index.html'), 'utf8');
const stamped = html.replaceAll('__BUILD_SHA__', sha);
if (stamped.split(sha).length !== 3) throw new Error('expected the sha in exactly 2 places (meta + footer)');
fs.writeFileSync(path.join(dist, 'index.html'), stamped);

fs.writeFileSync(
  path.join(dist, 'config.js'),
  `// Generated by build.mjs for build ${sha}.\nexport const API = ${JSON.stringify(API)};\nexport const SESSION = ${JSON.stringify(session)};\n`,
);
console.log(`built dist/ at ${sha}`);
